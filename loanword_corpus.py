def all_words():
    """카테고리 구분 없이 전체 단어 리스트."""
    out = []
    for ws in WORDS.values():
        out.extend(ws)
    return out


def generate_sentences(per_word=6, pair_ratio=0.15, seed=42):
    """
    각 단어를 '공통 + 소속 카테고리' carrier 풀에 끼워 발화 원문 리스트를 생성한다.

    Args:
      per_word:   단어당 생성할 문장 수 (풀에서 서로 다른 carrier 무작위 선택)
      pair_ratio: 전체 중 '외래어 2개' 문장의 비율 (같은 카테고리 내에서 쌍 선택)
      seed:       재현성

    Returns:
      list[str] — 발화 원문(맞춤법). G2P 라벨은 호출 측에서 생성.
    """
    rng = random.Random(seed)
    sentences = []

    for cat, ws in WORDS.items():
        pool = CARRIERS_COMMON + CARRIERS_BY_CAT[cat]
        for w in ws:
            chosen = rng.sample(pool, min(per_word, len(pool)))
            for c in chosen:
                sentences.append(render(c, {"w": w}))

    # 외래어 쌍 문장 추가 — 같은 카테고리 안에서만 짝을 짓는다
    pair_cats = [cat for cat, ws in WORDS.items() if len(ws) >= 2]
    n_pair = int(len(sentences) * pair_ratio)
    for _ in range(n_pair):
        cat = rng.choice(pair_cats)
        a, b = rng.sample(WORDS[cat], 2)
        c = rng.choice(CARRIERS_PAIR)
        sentences.append(render(c, {"a": a, "b": b}))

    rng.shuffle(sentences)
    # 중복 제거(고립 단어 carrier 가 겹칠 수 있음) — 순서 유지
    seen, uniq = set(), []
    for s in sentences:
        if s not in seen:
            seen.add(s)
            uniq.append(s)
    return uniq


