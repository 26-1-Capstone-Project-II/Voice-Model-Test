# 한 문장에 외래어 두 개 — 연속 OOV 커버용.
# 어떤 카테고리 쌍에도 의미가 성립하는 중립 템플릿만 남기고,
# 쌍 자체를 같은 카테고리 안에서 뽑아 "리소토 수치랑 라이프치히 수치" 류를 차단한다.
