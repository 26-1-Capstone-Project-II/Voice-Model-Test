# ────────────────────────────────────────────
# 0. 조사(받침) 처리 — "스노클링가"(X) → "스노클링이"(O)
#    템플릿에는 {이} {는} {를} {랑} 같은 마커를 쓰고, 앞 단어 끝 받침에 따라 고른다.
# ────────────────────────────────────────────
def _has_batchim(word):
    """단어의 마지막 한글 음절에 받침이 있으면 True. (외래어 끝의 영문/기호는 무시)"""
    for ch in reversed(word):
        if "가" <= ch <= "힣":
            return (ord(ch) - 0xAC00) % 28 != 0
    return False  # 한글이 없으면 받침 없음으로 간주

# 마커 → (받침 있을 때, 받침 없을 때)
_JOSA = {
    "{이}": ("이", "가"),
    "{은}": ("은", "는"),
    "{을}": ("을", "를"),
    "{과}": ("과", "와"),
    "{이랑}": ("이랑", "랑"),
    "{으로}": ("으로", "로"),  # ㄹ받침은 '로'지만 근사로 충분
}

# 슬롯({w}/{a}/{b})과 조사 마커를 한 번에 잡는 토큰 패턴
_TOKEN = re.compile(r"\{(w|a|b|" + "|".join(m.strip("{}") for m in _JOSA) + r")\}")

def render(template, slots):
    """
    템플릿을 렌더링한다. 조사 마커는 '바로 앞에 나온 단어 슬롯'의 받침에 맞춰 결정.
      예) render("{a}{이랑} {b}{을}", {"a": "데시벨", "b": "헤르츠"})
          → "데시벨이랑 헤르츠를"
    """
    state = {"last": ""}
    def repl(m):
        tok = m.group(1)
        if tok in slots:
            state["last"] = slots[tok]
            return slots[tok]
        yes, no = _JOSA["{" + tok + "}"]
        return yes if _has_batchim(state["last"]) else no
    return _TOKEN.sub(repl, template)


