# 한 문장에 외래어 두 개 — 연속 OOV 커버용
CARRIERS_PAIR = [
    "{a} 회의에서 {b} 이야기가 나왔어요.",
    "{a}하고 {b} 중에 뭐가 더 중요해요?",
    "{a} 작업이 끝나면 {b}{으로} 넘어갈게요.",
    "{a} 수치랑 {b} 수치를 같이 봐 주세요.",
    "오늘은 {a}{이랑} {b}{을} 다뤄 보겠습니다.",
]


def all_words():
    """카테고리 구분 없이 전체 단어 리스트."""
    out = []
    for ws in WORDS.values():
        out.extend(ws)
    return out


def generate_sentences(per_word=6, pair_ratio=0.15, seed=42):
    """
    각 단어를 carrier 에 끼워 발화 원문 리스트를 생성한다.

    Args:
      per_word:   단어당 생성할 문장 수 (서로 다른 carrier 무작위 선택)
      pair_ratio: 전체 중 '외래어 2개' 문장의 비율
      seed:       재현성

    Returns:
      list[str] — 발화 원문(맞춤법). G2P 라벨은 호출 측에서 생성.
    """
    rng = random.Random(seed)
    words = all_words()
    sentences = []

    for w in words:
        chosen = rng.sample(CARRIERS, min(per_word, len(CARRIERS)))
        for c in chosen:
            sentences.append(render(c, {"w": w}))

    # 외래어 쌍 문장 추가
    n_pair = int(len(sentences) * pair_ratio)
    for _ in range(n_pair):
        a, b = rng.sample(words, 2)
        c = rng.choice(CARRIERS_PAIR)
        sentences.append(render(c, {"a": a, "b": b}))

    rng.shuffle(sentences)
    # 중복 제거(고립 단어 carrier 가 겹칠 수 있음) — 순서 유지
    seen, uniq = set(), []
    for s in sentences:
        if s not in seen:
            seen.add(s)
            uniq.append(s)
    return uniq


